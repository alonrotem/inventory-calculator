import { Injectable } from '@angular/core';
import i18next from 'i18next';
import { environment } from '../../environments/environment';
import { TranslationKey } from './translation-keys';
import { BOOTSTRAP_CSS, STORAGE_DIRECTION, STORAGE_LANGUAGE, preferredLanguages, registerInitialLocale } from './language';

export interface LanguageInfo {
  code: string;
  name: string;
  nativeName: string;
  dir: 'ltr' | 'rtl';
}

interface LanguagesResponse { default: string; languages: LanguageInfo[]; }
interface BundleResponse { resources: Record<string, Record<string, any>>; }

const ENGLISH: LanguageInfo = { code: 'en', name: 'English', nativeName: 'English', dir: 'ltr' };

/**
 * The app's language. The translations are the server's (server/i18n), shared with the server side:
 * a key is '<namespace>:<path.to.key>', and the typed list of keys is generated by `npm run i18n:types` in the server folder.
 *
 * It loads before the first page is shown (see app.config.ts). Changing the language reloads the app,
 * so the text, the direction, the right Bootstrap stylesheet and Angular's number / date formats all start over together.
 */
@Injectable({ providedIn: 'root' })
export class TranslationService {
  language = 'en';
  dir: 'ltr' | 'rtl' = 'ltr';
  languages: LanguageInfo[] = [ENGLISH];

  private i18n = i18next.createInstance();

  get current(): LanguageInfo {
    return this.languages.find(l => l.code === this.language) ?? ENGLISH;
  }

  /** Translates a key. Plural and number formats come with the key: t('common:list.total', { count: 3 }). */
  t(key: TranslationKey, params?: Record<string, unknown>): string {
    return this.tx(key, params);
  }

  /** For keys made at runtime ('status:' + name), which can't be checked in advance. */
  tx(key: string, params?: Record<string, unknown>): string {
    // before init() (or without the server) the key itself is shown
    const text = this.i18n.isInitialized ? this.i18n.t(key, params as any) : key;
    return typeof text === 'string' ? text : key;
  }

  /** A quantity of raw material with its unit: kilos with two decimals, units as a whole number. */
  quantity(value: number | null | undefined, units: string | null | undefined): string {
    if (value == null || (value as unknown) === '') return '';
    return this.t(units === 'kg' ? 'common:quantity.kg' : 'common:quantity.units', { value });
  }

  /** Text for a value that comes from the database: the translation of prefix + value, or the value itself when there is none. */
  enumLabel(prefix: string, value: string | null | undefined): string {
    if (value == null || value === '') return '';
    if (!this.i18n.isInitialized) return String(value);
    // the value as it is, or in lower case with underscores ('Dark Brown' -> 'dark_brown')
    for (const name of [String(value), String(value).toLowerCase().replace(/\s+/g, '_')]) {
      if (this.i18n.exists(prefix + name)) return this.tx(prefix + name);
    }
    return String(value);
  }

  async init(): Promise<void> {
    const info = await this.fetchJson<LanguagesResponse>('/i18n/languages').catch(() => null);
    this.languages = info?.languages?.length ? info.languages : [ENGLISH];
    const fallback = info?.default ?? ENGLISH.code;
    this.language = this.choose(fallback);
    this.dir = this.current.dir;

    // without the server, the keys themselves are shown
    const bundle = await this.fetchJson<BundleResponse>(`/i18n/bundle/${this.language}`).catch(() => null);
    const resources = bundle?.resources ?? {};
    await this.i18n.init({
      lng: this.language,
      fallbackLng: fallback,
      supportedLngs: this.languages.map(l => l.code),
      resources,
      ns: [...new Set(Object.values(resources).flatMap(r => Object.keys(r)))],
      defaultNS: 'common',
      interpolation: { escapeValue: false },   // Angular escapes what it shows (never put a translation into [innerHTML])
      returnNull: false
    });

    await registerInitialLocale();
    this.applyToDocument();
  }

  /** Saves the choice and reloads the app in the new language. */
  setLanguage(code: string) {
    const language = this.languages.find(l => l.code === code);
    if (!language || code === this.language) {
      return;
    }
    try {
      localStorage.setItem(STORAGE_LANGUAGE, code);
      localStorage.setItem(STORAGE_DIRECTION, language.dir);
    }
    catch { /* storage blocked: the browser's language is used */ }
    location.reload();
  }

  /** The saved language, else the browser's, else the default. */
  private choose(fallback: string): string {
    const supported = new Set(this.languages.map(l => l.code));
    for (const tag of preferredLanguages()) {
      const lower = tag.toLowerCase();
      if (supported.has(lower)) return lower;
      if (supported.has(lower.split('-')[0])) return lower.split('-')[0];
    }
    return fallback;
  }

  private applyToDocument() {
    const html = document.documentElement;
    html.lang = this.language;
    html.dir = this.dir;
    try {
      localStorage.setItem(STORAGE_DIRECTION, this.dir);
    }
    catch { /* storage blocked */ }

    // Bootstrap has a separate stylesheet for right-to-left (index.html loads the right one, this is for a first visit)
    const wanted = BOOTSTRAP_CSS[this.dir];
    const link = document.getElementById('bootstrap-css') as HTMLLinkElement | null;
    if (link && link.getAttribute('href') !== wanted) {
      link.setAttribute('href', wanted);
    }
  }

  private async fetchJson<T>(path: string): Promise<T> {
    const response = await fetch(environment.serverUrl + path, { headers: { Accept: 'application/json' } });
    if (!response.ok) {
      throw new Error(`${path}: ${response.status}`);
    }
    return response.json();
  }
}
